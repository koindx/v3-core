// Builds every contract of this repository, mirroring `koinos-sdk-as-cli build-all`:
//   1. ABI generation (abi/<name>.abi and abi/<name>-abi.json in koilib v5 format)
//   2. AssemblyScript protobuf classes for every proto in assembly/proto
//   3. index.ts dispatcher (koinos-as-gen)
//   4. wasm compilation (build/<mode>/contract.wasm)
//
// usage: node scripts/build.js <debug|release> [contract names...]
// (every contract by default; package.json has a script per contract, e.g. `yarn build:release:pool`)
const path = require("path");
const fs = require("fs");
const crypto = require("crypto");
const { execSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const bin = (name) => path.join(root, "node_modules", ".bin", name);

// the pool must be compiled before the factory (the factory embeds the hash of the pool bytecode)
const CONTRACTS = [
  { name: "pool", dir: "contracts/pool", proto: "pool.proto" },
  { name: "factory", dir: "contracts/factory", proto: "factory.proto" },
];

const mode = process.argv[2] || "release";
if (!["debug", "release"].includes(mode)) {
  console.error(`invalid build mode "${mode}", use debug or release`);
  process.exit(1);
}
const filter = process.argv.slice(3);
for (const name of filter) {
  if (!CONTRACTS.some((c) => c.name === name)) {
    console.error(`unknown contract "${name}", use: ${CONTRACTS.map((c) => c.name).join(", ")}`);
    process.exit(1);
  }
}
// the factory embeds the hash of the pool bytecode: building the factory builds the pool first, so
// the hash is always the one of the current pool sources
if (filter.includes("factory") && !filter.includes("pool")) {
  console.log("the factory embeds the hash of the pool: building the pool first");
  filter.push("pool");
}
const contracts = CONTRACTS.filter((c) => filter.length === 0 || filter.includes(c.name));

// like `yarn run`, expose the local binaries (koinos-abi-proto-gen spawns `protoc` from the PATH)
const env = { ...process.env, PATH: `${path.join(root, "node_modules", ".bin")}${path.delimiter}${process.env.PATH}` };

function run(cmd, cwd, extraEnv = {}) {
  console.log(`\x1b[34m${cmd}\x1b[0m`);
  execSync(cmd, { stdio: "inherit", cwd, env: { ...env, ...extraEnv } });
}

// every contract implements the `authorize` entry point (koinos-sdk-as-cli --generate_authorize):
// they are deployed overriding their own authority and always deny it
const AUTHORIZE = { GENERATE_AUTHORIZE_ENTRY_POINT: "1" };

/**
 * the protoc plugins (node scripts) read their input with fs.readFileSync(stdin), which sometimes
 * fails with EAGAIN when the pipe is not ready yet: the generation is retried
 */
function runWithRetries(cmd, cwd, extraEnv = {}, attempts = 10) {
  for (let i = 1; ; i++) {
    try {
      run(cmd, cwd, extraEnv);
      return;
    } catch (error) {
      if (i >= attempts) throw error;
      console.log(`retrying (${i}/${attempts - 1})...`);
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 200 * i); // sleep
    }
  }
}

/**
 * koinos-abi-proto-gen resolves `import "koinos/options.proto"` relative to the working
 * directory, so the shared proto dependencies are linked into every contract folder
 */
function linkProtoDependencies(cwd) {
  for (const dep of ["koinos", "google"]) {
    const link = path.join(cwd, dep);
    if (!fs.existsSync(link)) {
      fs.symlinkSync(path.relative(cwd, path.join(root, "proto", dep)), link, "dir");
    }
  }
}

/**
 * Repeated numbers must be declared `[packed = true]`: as-proto-gen only generates packed
 * encoders/decoders when the option is present (otherwise it reads and writes the unpacked
 * proto2 format), while koilib/protobufjs and the other Koinos tools use the proto3 default
 * (packed). Without the option the contracts silently misread the arrays sent by the clients.
 */
function checkPackedRepeatedNumbers(protoFile) {
  const numeric = "(?:u?int32|u?int64|sint32|sint64|s?fixed32|s?fixed64|bool|float|double)";
  const lines = fs.readFileSync(protoFile, "utf8").split("\n");
  lines.forEach((line, i) => {
    if (new RegExp(`^\\s*repeated\\s+${numeric}\\s`).test(line) && !/packed\s*=\s*true/.test(line)) {
      console.error(`${path.relative(root, protoFile)}:${i + 1}: repeated numbers must be [packed = true]`);
      process.exit(1);
    }
  });
}

/**
 * The packed decoders generated by as-proto-gen compute the end of the array with
 * `reader.ptr + reader.uint32()`: `reader.ptr` is read before the length varint is consumed, so
 * the array ends one byte too early and a last element of one byte (e.g. `[0]`, or a fee of 100
 * at the end of a path) is lost and then parsed as a field tag. The operands are swapped so the
 * length is read first.
 */
function fixPackedDecoders(files) {
  for (const file of files) {
    const source = fs.readFileSync(file, "utf8");
    const fixed = source.split("reader.ptr + reader.uint32()").join("reader.uint32() + reader.ptr");
    if (fixed !== source) fs.writeFileSync(file, fixed);
  }
}

/** generated AssemblyScript files of a proto folder */
function generatedFiles(dir) {
  return fs.readdirSync(dir).filter((f) => f.endsWith(".ts")).map((f) => path.join(dir, f));
}

/** converts the ABI generated by koinos-abi-proto-gen to the format expected by koilib v5 */
function normalizeAbi(file) {
  const abi = JSON.parse(fs.readFileSync(file, "utf8"));
  for (const method of Object.values(abi.methods)) {
    const rename = { input: "argument", output: "return", entryPoint: "entry_point", readOnly: "read_only" };
    for (const [from, to] of Object.entries(rename)) {
      if (Object.prototype.hasOwnProperty.call(method, from)) {
        method[to] = method[from];
        delete method[from];
      }
    }
  }
  fs.writeFileSync(file, JSON.stringify(abi, null, 2));
}

const includes = "-I.";

// phase 1: code generation of the selected contracts
for (const contract of contracts) {
  const cwd = path.join(root, contract.dir);
  if (!fs.existsSync(path.join(cwd, "assembly", "proto", contract.proto))) continue;
  console.log(`\x1b[32mGenerating ${contract.name}...\x1b[0m`);
  fs.mkdirSync(path.join(cwd, "abi"), { recursive: true });
  linkProtoDependencies(cwd);
  checkPackedRepeatedNumbers(path.join(cwd, "assembly", "proto", contract.proto));
  runWithRetries(`${bin("protoc")} ${includes} --plugin=protoc-gen-abi=${bin("koinos-abi-proto-gen")} --abi_out=abi/ assembly/proto/${contract.proto} koinos/chain/authority.proto`, cwd, AUTHORIZE);
  normalizeAbi(path.join(cwd, "abi", `${contract.name}-abi.json`));
  runWithRetries(`${bin("protoc")} ${includes} --plugin=protoc-gen-as=${bin("as-proto-gen")} --as_out=. assembly/proto/*.proto`, cwd);
  fixPackedDecoders(generatedFiles(path.join(cwd, "assembly", "proto")));
  runWithRetries(`${bin("protoc")} ${includes} --plugin=protoc-gen-as=${bin("koinos-as-gen")} --as_out=assembly/ assembly/proto/${contract.proto}`, cwd, AUTHORIZE);
}

/**
 * The factory only accepts pools whose bytecode matches the sha256 multihash (0x12 0x20 + digest)
 * of the pool built in the same mode, so it is written to contracts/factory/assembly/PoolHash.ts
 */
function writePoolHash() {
  const wasm = path.join(root, "contracts", "pool", "build", mode, "contract.wasm");
  if (!fs.existsSync(wasm)) {
    console.error(`${path.relative(root, wasm)} not found, build the pool first`);
    process.exit(1);
  }
  const digest = crypto.createHash("sha256").update(fs.readFileSync(wasm)).digest();
  const multihash = [0x12, 0x20, ...digest];
  const content = `// Generated by scripts/build.js from the ${mode} build of the pool, do not edit.
// sha256 multihash of the pool bytecode accepted by the factory: 0x${Buffer.from(multihash).toString("hex")}
const POOL_BYTECODE_HASH: StaticArray<u8> = [${multihash.join(", ")}];

export function poolBytecodeHash(): Uint8Array {
  const hash = new Uint8Array(POOL_BYTECODE_HASH.length);
  for (let i = 0; i < POOL_BYTECODE_HASH.length; i++) hash[i] = POOL_BYTECODE_HASH[i];
  return hash;
}
`;
  fs.writeFileSync(path.join(root, "contracts", "factory", "assembly", "PoolHash.ts"), content);
  console.log(`  pool bytecode hash: 0x${Buffer.from(multihash).toString("hex")}`);
}

/**
 * The contracts are compiled with the `stub` runtime (bump allocator, memory is never freed):
 * a contract call is short lived (Koinos allows 512 pages = 32 MiB) and the incremental GC of
 * AssemblyScript 0.19 freed live objects in some calls (corrupted strings returned by
 * pool.get_populated_ticks after a tick crossing swap). Running out of memory reverts the call.
 */
const RUNTIME = "stub";

/**
 * Runtime errors of AssemblyScript (index out of range, null dereference...) call `abort`, which
 * is removed in the deployed builds (plain trap). DEBUG_ABORT=1 compiles utils/Abort.ts instead,
 * so they revert with the message and source location: only for local debugging, the bytecode
 * (and so the pool hash) is different.
 */
function abortOptions(cwd) {
  if (process.env.DEBUG_ABORT !== "1") return "--use abort=";
  const file = path.relative(cwd, path.join(root, "utils", "Abort.ts")).split(path.sep).join("/");
  return `${file} --use abort=${file.replace(/\.ts$/, "")}/revertOnAbort`;
}

// phase 2: compilation
for (const contract of contracts) {
  const cwd = path.join(root, contract.dir);
  if (contract.name === "factory") writePoolHash();
  console.log(`\x1b[32mCompiling ${contract.name} (${mode})...\x1b[0m`);
  run(
    `node ${path.join(root, "node_modules", "assemblyscript", "bin", "asc")} assembly/index.ts ${abortOptions(cwd)} --target ${mode} --runtime ${RUNTIME} --use BUILD_FOR_TESTING=0 --disable sign-extension --config asconfig.json`,
    cwd
  );
  const wasm = path.join(cwd, "build", mode, "contract.wasm");
  // read by the deployment scripts, which refuse the DEBUG_ABORT builds
  fs.writeFileSync(path.join(cwd, "build", mode, "build.json"), JSON.stringify({ debugAbort: process.env.DEBUG_ABORT === "1" }, null, 2));
  console.log(`  ${path.relative(root, wasm)}: ${fs.statSync(wasm).size} bytes`);
}
